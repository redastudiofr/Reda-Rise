// Generates src/lib/network/franceOutline.ts from Natural Earth (public domain),
// via the world-atlas package. Run: node scripts/build-france-outline.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-50m.json', import.meta.url)));
const countries = feature(topo, topo.objects.countries);
const france = countries.features.find((f) => f.properties.name === 'France');
// Metropolitan France and Corsica only: keep rings inside a lon/lat box.
const inBox = (ring) => ring.every(([lon, lat]) => lon > -6 && lon < 10 && lat > 41 && lat < 51.5);
const rings = france.geometry.coordinates.map((poly) => poly[0]).filter(inBox);
const round = (v) => Math.round(v * 1000) / 1000;
const data = rings.map((r) => r.map(([lon, lat]) => [round(lon), round(lat)]));
const out = `/**
 * Outline of metropolitan France and Corsica, [longitude, latitude] pairs.
 * Source: Natural Earth 1:50m (public domain) via the world-atlas package.
 * Generated by scripts/build-france-outline.mjs — do not edit by hand.
 */
export const FRANCE_RINGS: [number, number][][] = ${JSON.stringify(data)};
`;
writeFileSync(new URL('../src/lib/network/franceOutline.ts', import.meta.url), out);
console.log('rings', data.length, 'points', data.reduce((a, r) => a + r.length, 0), 'bytes', out.length);
